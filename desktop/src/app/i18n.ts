const dictionaries: Record<LanguageCode, TranslationDict> = { zh, en };

export type Translator = (key: TranslationKey, values?: TranslationValues) => string;

export function normalizeLanguage(value: string | null | undefined): LanguageCode {
  return value === "en" ? "en" : "zh";
}

export function createTranslator(language: string | null | undefined): Translator {
  const dict = dictionaries[normalizeLanguage(language)];
  return (key, values) => interpolate(dict[key] ?? zh[key] ?? key, values);
}

function interpolate(template: string, values: TranslationValues = {}): string {
  return template.replace(/\{(\w+)\}/g, (match, name) => String(values[name] ?? match));
}
